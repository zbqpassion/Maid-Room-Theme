"""把人物从插画里抠出来，生成 tools/source/mask.png（白 = 人物）。

做法：OpenCV GrabCut。先用颜色给出确定的前景种子（橙色头发、黑色裙身），
再用手工标的多边形补充确定前景（白袜、围裙）和确定背景（床、地板、窗、灯），
其余交给 GrabCut 按颜色和边缘判断。坐标都是原图 941x1672 的像素。

用法：python tools/cutout.py [预览图输出路径]
"""
import os
import sys

import cv2
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'source', 'maid.webp')
OUT = os.path.join(HERE, 'source', 'mask.png')

rgb = np.array(Image.open(SRC).convert('RGB'))
h, w = rgb.shape[:2]
bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
hsv = cv2.cvtColor(rgb, cv2.COLOR_RGB2HSV)
H, S, V = hsv[:, :, 0].astype(int), hsv[:, :, 1].astype(int), hsv[:, :, 2].astype(int)
yy, xx = np.mgrid[0:h, 0:w]

mask = np.full((h, w), cv2.GC_PR_BGD, np.uint8)
# 人物大致范围内先设为“可能是前景”
mask[60:1630, 90:w] = cv2.GC_PR_FGD

# 确定背景：手工多边形
BG = [
    [(0, 0), (300, 0), (300, 150), (291, 200), (289, 300), (291, 400), (281, 450), (270, 500), (245, 550), (224, 600), (120, 700), (0, 700)],          # 窗、灯、床头柜
    [(560, 0), (941, 0), (941, 380), (720, 330), (640, 250), (600, 120)],                  # 右上墙、画、床头
    [(0, 700), (95, 700), (95, 1000), (60, 1150), (150, 1260), (150, 1380), (120, 1460), (105, 1500), (100, 1672), (0, 1672)],  # 左侧床沿和地板
    [(100, 1600), (941, 1600), (941, 1672), (100, 1672)],                                  # 最底下地毯
    [(520, 1300), (941, 1300), (941, 1672), (520, 1672)],                                  # 右下地板
    [(500, 1300), (520, 1300), (520, 1445), (465, 1445), (470, 1400), (485, 1350)],        # 右脚右侧地板
    [(265, 1305), (383, 1305), (370, 1350), (348, 1395), (345, 1445), (240, 1445), (245, 1400), (250, 1350)],  # 两腿之间的地板
    [(345, 1445), (520, 1445), (520, 1672), (235, 1672), (235, 1560), (232, 1500), (240, 1445)],              # 右脚下方地板
    [(380, 1030), (397, 1030), (398, 1150), (393, 1250), (385, 1300), (267, 1300), (282, 1250), (307, 1200), (337, 1150), (359, 1100), (372, 1060)],  # 两腿之间的床单
    [(100, 1110), (140, 1150), (185, 1200), (178, 1250), (168, 1300), (150, 1300), (150, 1260), (60, 1150)],  # 左腿左侧床单
    [(515, 1020), (555, 1020), (558, 1060), (580, 1150), (590, 1220), (600, 1300), (500, 1300), (500, 1250), (485, 1200), (495, 1150), (505, 1100)],  # 右腿右侧床单
    [(165, 815), (200, 810), (205, 850), (170, 870), (162, 840)],                          # 发丝之间露出的床
    [(760, 380), (941, 400), (941, 560), (800, 520)],                                      # 枕头
]
# 确定前景：手工多边形（白袜、围裙、脸和手、浅色发丝，颜色和床单太接近）
FG = [
    [(250, 1050), (360, 1050), (320, 1150), (265, 1250), (250, 1300), (225, 1400), (212, 1540), (140, 1560), (135, 1500), (160, 1400), (185, 1300), (205, 1200), (232, 1100)],  # 左腿袜子
    [(410, 880), (495, 880), (485, 1100), (468, 1200), (478, 1290), (445, 1400), (372, 1415), (395, 1300), (410, 1200), (415, 1100)],  # 右腿袜子
    [(220, 900), (370, 900), (360, 1050), (250, 1050)],                                    # 左大腿
    [(400, 720), (540, 720), (540, 860), (420, 860)],                                      # 膝盖
    [(350, 200), (520, 200), (520, 340), (400, 350)],                                      # 脸
    [(420, 480), (620, 480), (620, 580), (420, 580)],                                      # 胸前
    [(330, 80), (480, 80), (480, 130), (330, 150)],                                        # 头饰
    [(600, 780), (760, 800), (760, 1050), (620, 1000)],                                    # 右侧围裙
    [(318, 215), (345, 200), (345, 480), (330, 560), (310, 560), (320, 400)],              # 脸左侧的浅色发丝
    [(335, 700), (400, 690), (400, 790), (345, 800), (330, 770)],                          # 左手袖口褶边
    [(230, 820), (300, 790), (305, 880), (215, 900), (175, 895), (200, 860)],              # 左侧围裙褶边
    [(100, 1045), (150, 1060), (205, 1110), (200, 1180), (175, 1150), (130, 1100), (95, 1070)],  # 左下裙摆褶边
    [(440, 630), (560, 640), (545, 700), (430, 700)],                                      # 腿上的围裙
    [(705, 670), (760, 690), (770, 800), (700, 790)],                                      # 右侧围裙上半
    [(790, 810), (860, 800), (941, 830), (941, 880), (880, 870), (810, 860)],              # 右侧围裙褶边
    [(880, 945), (941, 935), (941, 1000), (900, 1000)],                                    # 最右侧裙摆褶边
    [(590, 1050), (650, 1040), (675, 1100), (680, 1190), (640, 1195), (610, 1150)],        # 右腿旁的多层褶边
    [(680, 1235), (780, 1225), (775, 1275), (700, 1285), (675, 1260)],                     # 裙底褶边
]
for poly in BG:
    cv2.fillPoly(mask, [np.array(poly, np.int32)], cv2.GC_BGD)
for poly in FG:
    cv2.fillPoly(mask, [np.array(poly, np.int32)], cv2.GC_FGD)

# 确定前景：颜色种子
hair = (H >= 6) & (H <= 20) & (S > 150) & (V > 150) & (yy < 1000) & (xx > 95)
dress = (V < 75) & (yy > 100) & (yy < 1300) & (xx > 100)
mask[hair & (mask != cv2.GC_BGD)] = cv2.GC_FGD
mask[dress & (mask != cv2.GC_BGD)] = cv2.GC_FGD

bgd, fgd = np.zeros((1, 65), np.float64), np.zeros((1, 65), np.float64)
cv2.grabCut(bgr, mask, None, bgd, fgd, 8, cv2.GC_INIT_WITH_MASK)
fg = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)

# 清理：去小碎块、填小洞
k5 = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, k5)
fg = cv2.morphologyEx(fg, cv2.MORPH_CLOSE, k5)
n, labels, stats, _ = cv2.connectedComponentsWithStats(fg, connectivity=8)
keep = np.zeros_like(fg)
for i in range(1, n):
    if stats[i, cv2.CC_STAT_AREA] > 1500:
        keep[labels == i] = 255
fg = keep
# 填掉人物内部的小洞（刺绣花心之类被误判成背景的点）
contours, hier = cv2.findContours(fg, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
for i, c in enumerate(contours):
    if hier[0][i][3] != -1 and cv2.contourArea(c) < 500:
        cv2.drawContours(fg, [c], -1, 255, -1)
Image.fromarray(fg).save(OUT)
print('前景占比', round(float((fg > 0).mean()), 3))

if len(sys.argv) > 1:
    # 预览：背景压成洋红，方便看抠得准不准
    prev = rgb.copy()
    prev[fg == 0] = (prev[fg == 0] * 0.25 + np.array([255, 0, 255]) * 0.75).astype(np.uint8)
    Image.fromarray(prev).save(sys.argv[1], quality=88)
